import * as React from "react";

import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      // min-w-0 (Phase H): a grid/flex ITEM defaults to min-width:auto, which
      // refuses to shrink below its content's intrinsic width. A card holding a
      // wide table therefore blew its grid track out past the viewport — the
      // track computed to 578.5px inside a 343px container on a 375px screen —
      // so the table's own `overflow-auto` wrapper never got to scroll and the
      // PAGE scrolled sideways instead. Measured on all 6 clients' summary tab
      // (+90 to +220px). For a normal block box min-width:auto already resolves
      // to 0, so this is a no-op everywhere except the flex/grid case it fixes.
      "min-w-0 rounded-card border bg-card text-card-foreground shadow",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

